const days = [];
for (let day = 1; day <= 84; day++) {
  const week = Math.ceil(day / 7);
  const g = syllabus.grammar.filter(x => x.day === day);
  const fixed = FIXED[day] || {};
  let rec = { day, week, kind: fixed.kind || 'learn' };
  if (fixed.title) Object.assign(rec, { title: fixed.title, desc: fixed.desc, tips: fixed.tips });
  else if (syllabus.reviewDays.includes(day)) {
    rec.kind = 'review';
    rec.title = `${week}주차 총정리`;
    rec.desc = `${week}주차에 배운 내용을 복습하고 주간 테스트를 봅니다.`;
    rec.tips = REVIEW_TIPS;
  } else if (g.length) {
    rec.title = g.map(x => x.titleKo).join(' · ');
    rec.desc = `문법: ${g.map(x => x.title).join(', ')}`;
  }
  if (rec.kind !== 'learn' && day === 7) rec.kind = 'review';
  if ([7, 14].includes(day)) rec.kind = 'review';
  if (THEME[day]) rec.theme = THEME[day];
  if (!rec.tips) delete rec.tips;
  days.push(rec);
}

writeFileSync(join(ROOT, 'data/curriculum.json'), JSON.stringify({ totalDays: 84, weeks: WEEKS, days }, null, 1) + '\n');
console.log(`curriculum.json: ${days.length}일, ${WEEKS.length}주`);
const untitled = days.filter(d => !d.title).map(d => d.day);
if (untitled.length) console.log('제목 없는 day:', untitled.join(', '));
