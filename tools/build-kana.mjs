function push(script, prefix, group, row, col, key, kana, romaji, ko, day) {
  const w = WORDS[kana];
  const item = { id: `${prefix}-${key}`, kana, romaji, ko, script, group, row, col, day };
  if (w && !w[1].startsWith('(')) item.word = { kana: w[0], ko: w[1] };
  else if (w) item.rare = w[1].replace(/[()]/g, '');
  const conf = CONFUSE.filter(g => [...g].includes(kana)).flatMap(g => [...g]).filter(c => c !== kana && c !== 'ヵ');
  if (conf.length) item.confuse = [...new Set(conf)];
  if (TIPS[key] && !(script === 'katakana' && ['ha', 'he', 'wo'].includes(key))) item.tip = TIPS[key];
  if (script === 'katakana' && key === 'wo') item.tip = "현대 일본어에서는 거의 쓰이지 않습니다. 모양만 알아 두면 충분합니다.";
  out.push(item);
}

for (const [script, prefix, idx, days] of [['hiragana', 'hi', 3, HIRA_DAY], ['katakana', 'ka', 4, KATA_DAY]]) {
  for (const r of BASIC) {
    const chars = [...r[idx]];
    r[1].forEach((rom, c) => { if (rom) push(script, prefix, 'basic', r[0], c, rom, chars[c], rom, r[2][c], days[r[0]]); });
  }
  const dDay = script === 'hiragana' ? 4 : 11;
  for (const r of DAKU) {
    const chars = [...r[idx]];
    r[1].forEach((rom, c) => push(script, prefix, r[5], r[0], c, rom, chars[c], rom === 'di' ? 'ji' : rom === 'du' ? 'zu' : rom, r[2][c], dDay));
  }
  const yDay = script === 'hiragana' ? 5 : 11;
  for (const r of YOON) r[1].forEach((rom, c) => push(script, prefix, 'yoon', r[0], c, rom, r[idx][c], rom, r[2][c], yDay));
}
for (const [key, rom, ko, kana, word, wko] of EXT) {
  out.push({ id: `ka-${key}`, kana, romaji: rom, ko, script: 'katakana', group: 'ext', row: 'ext', col: 0, day: 12, word: { kana: word, ko: wko } });
}

